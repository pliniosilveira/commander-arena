/**
 * The hidden test decks (SPEC 17.6 A27, D-137). They are test fixtures and are NEVER offered to
 * players: the menu, the import screen's opponent list and the sample deck come from the real
 * precon snapshots (`src/precons/`). A hidden deck starts only by id, with
 * `?autostart=<human id>,<ai id>`, which the end-to-end tests and quick manual checks use; it is
 * the one way to start a game from a deck that is not a valid, fully supported Commander deck.
 *
 * The decks are 100 cards each, built from the engine's fixture cards, so they are not singleton
 * and ignore color identity. Every card in them that is not a real fixture is SYNTHETIC and says
 * so in its name. The first three (`white-knights`, `swamp-forest`, `instants`) are built from real
 * fixture cards only.
 *
 * Nothing imports this module statically: it is a chunk of its own, loaded by `game/host.ts` and
 * `precons/start.ts` only when a game starts from one of these ids, so the production bundle
 * carries no test deck and no SYNTHETIC card (the engine package is marked `sideEffects: false`).
 */
