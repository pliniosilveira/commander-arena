/** True for the id of a hidden test deck. */
export function isHiddenDeckId(id: string): boolean {
  return HIDDEN_DECKS.some((deck) => deck.id === id);
}

/** A hidden test deck by id; throws for any other id (real precons are prepared by the page). */
export function preconById(id: string): Precon {
  const found = HIDDEN_DECKS.find((p) => p.id === id);
  if (found === undefined) throw new Error(`Unknown hidden test deck: ${id}`);
  return found;
}

/** The engine deck for a precon: the commander first (index 0), then the 99 other cards. */
export function deckFor(precon: Precon): DeckConfig {
  const cards: CardDefinition[] = deckOf([[precon.commander, 1], ...precon.entries]);
  return { cards, commanders: [0] };
}
