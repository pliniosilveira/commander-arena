// `pnpm planeswalker-types:generate`: reads CR 205.3j (the list of planeswalker types) from the repository's copy of the
// Comprehensive Rules, `docs/rules/comprehensive-rules.txt`, plus the planeswalker types that an applied Update Bulletin of
// `docs/rules/bulletins/` adds to 205.3j and that the CR file does not hold yet, and writes the table the engine uses to tell
// a planeswalker type from a creature type, `packages/engine/src/data/planeswalker-types.ts` (D-200). The list is never typed
// by hand: `planeswalker-types.test.ts` parses the sources again and compares. `--check` compares without writing.
// Node built-ins only.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CR_FILE, REPO_ROOT } from './generate.ts';

export const BULLETINS_DIR = path.join(REPO_ROOT, 'docs', 'rules', 'bulletins');
export const PLANESWALKER_TABLE_FILE = path.join(
  REPO_ROOT,
  'packages',
  'engine',
  'src',
  'data',
  'planeswalker-types.ts',
);

const INTRO = 'The planeswalker types are ';
const BULLETIN_LINE =
  /\*\*205\.3j\*\* This release added [a-z]+ new planeswalker subtypes: ([^.]+)\./;

function splitList(list: string): string[] {
  const parts = list.split(/, (?:and )?| and /);
  for (const t of parts) {
    if (!/^[A-Za-z’-]+$/.test(t))
      throw new Error(`Unexpected planeswalker type ${JSON.stringify(t)}`);
  }
  return parts;
}

/** The planeswalker types of CR 205.3j, in the order the rule lists them. */
export function parseRulePlaneswalkerTypes(crText: string): string[] {
  const rule = crText.split(/\r?\n/).find((l) => l.startsWith('205.3j '));
  if (rule === undefined) throw new Error('Rule 205.3j is not in the rules text');
  const start = rule.indexOf(INTRO);
  if (start < 0) throw new Error('Rule 205.3j no longer has the list sentence');
  const list = rule.slice(start + INTRO.length);
  if (!list.endsWith('.')) throw new Error('Rule 205.3j does not end with a full stop');
  const body = list.slice(0, -1);
  const lastComma = body.lastIndexOf(', and ');
  if (lastComma < 0) throw new Error('Rule 205.3j no longer ends its list with ", and <type>"');
  return splitList(body);
}

/** The planeswalker types an Update Bulletin text adds to 205.3j (empty when it does not). */
export function parseBulletinPlaneswalkerTypes(bulletinText: string): string[] {
  const m = BULLETIN_LINE.exec(bulletinText);
  return m?.[1] === undefined ? [] : splitList(m[1]);
}

/** Every planeswalker type, sorted by code unit, without duplicates. */
export function planeswalkerTypes(crText: string, bulletins: readonly string[]): string[] {
  const all = [
    ...parseRulePlaneswalkerTypes(crText),
    ...bulletins.flatMap(parseBulletinPlaneswalkerTypes),
  ];
  return [...new Set(all)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function renderPlaneswalkerTable(types: readonly string[]): string {
  return [
    '/**',
    ' * GENERATED by `pnpm planeswalker-types:generate` (tools/creature-types/generate-planeswalker.ts) from CR 205.3j in',
    ' * docs/rules/comprehensive-rules.txt and from the planeswalker types an Update Bulletin of docs/rules/bulletins/ adds',
    ' * to 205.3j. Do not edit by hand: tools/creature-types/planeswalker-types.test.ts parses the sources again and fails',
    ' * when this table differs.',
    ' */',
    'export const PLANESWALKER_TYPES: readonly string[] = [',
    ...types.map((t) => `  '${t}',`),
    '];',
    '',
  ].join('\n');
}

export function readBulletins(): string[] {
  return readdirSync(BULLETINS_DIR)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => readFileSync(path.join(BULLETINS_DIR, f), 'utf8'));
}

function main(): void {
  const text = renderPlaneswalkerTable(
    planeswalkerTypes(readFileSync(CR_FILE, 'utf8'), readBulletins()),
  );
  if (process.argv.includes('--check')) {
    if (readFileSync(PLANESWALKER_TABLE_FILE, 'utf8') !== text) {
      console.error(
        'packages/engine/src/data/planeswalker-types.ts is out of date: run the generator',
      );
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(PLANESWALKER_TABLE_FILE, text);
  console.log(`Wrote ${PLANESWALKER_TABLE_FILE}`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
