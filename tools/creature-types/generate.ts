// `pnpm creature-types:generate`: reads CR 205.3m (the list of creature types) from the repository's
// copy of the Comprehensive Rules, `docs/rules/comprehensive-rules.txt`, and writes the table the
// engine uses for "choose a creature type", `packages/engine/src/data/creature-types.ts` (D-100). The
// list is never typed by hand: `creature-types.test.ts` parses the rules text again and compares, so
// the table cannot drift from the rules. `--check` compares without writing (exit 1 on a difference).
// Node built-ins only.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(here, '..', '..');
export const CR_FILE = path.join(REPO_ROOT, 'docs', 'rules', 'comprehensive-rules.txt');
export const TABLE_FILE = path.join(
  REPO_ROOT,
  'packages',
  'engine',
  'src',
  'data',
  'creature-types.ts',
);

const ONE_WORD_INTRO = 'All other creature types are one word long: ';
const TWO_WORD = /One creature type is two words long: ([^.]+)\./;

/** The text of rule 205.3m (one line of the rules file), or an error that says what is wrong. */
function ruleText(crText: string): string {
  const line = crText.split(/\r?\n/).find((l) => l.startsWith('205.3m '));
  if (line === undefined) throw new Error('Rule 205.3m is not in the rules text');
  return line;
}

/**
 * The creature types of CR 205.3m, in the order the rule lists them, with the one two-word type
 * ("Time Lord") placed where it sorts. The one-word types come from the sentence "All other creature
 * types are one word long: A, B, ..., and Z."; the two-word one from "One creature type is two words
 * long: X." Anything else in the rule's text is an error, so a change to its wording is noticed.
 */
export function parseCreatureTypes(crText: string): string[] {
  const rule = ruleText(crText);
  const start = rule.indexOf(ONE_WORD_INTRO);
  if (start < 0) throw new Error('Rule 205.3m no longer has the one-word list sentence');
  const list = rule.slice(start + ONE_WORD_INTRO.length);
  if (!list.endsWith('.')) throw new Error('Rule 205.3m does not end with a full stop');
  const parts = list.slice(0, -1).split(', ');
  const last = parts.pop();
  if (last === undefined || !last.startsWith('and ')) {
    throw new Error('Rule 205.3m no longer ends its list with ", and <type>"');
  }
  const oneWord = [...parts, last.slice('and '.length)];
  const two = TWO_WORD.exec(rule)?.[1];
  if (two === undefined) throw new Error('Rule 205.3m no longer names its two-word creature type');
  for (const t of oneWord) {
    if (!/^[A-Za-z’-]+$/.test(t)) throw new Error(`Unexpected creature type ${JSON.stringify(t)}`);
  }
  if (new Set(oneWord).size !== oneWord.length) throw new Error('A creature type is listed twice');
  // Code-unit order, never a locale: the list is sorted by name apart from a few apostrophe names.
  const at = oneWord.findIndex((t) => t > two);
  return at < 0 ? [...oneWord, two] : [...oneWord.slice(0, at), two, ...oneWord.slice(at)];
}

/** The generated module's text for `types`, one per line (stable under the formatter). */
export function renderTable(types: readonly string[]): string {
  for (const t of types) {
    if (t.includes("'") || t.includes('\\')) throw new Error(`Cannot write ${t} as a string`);
  }
  return [
    '/**',
    ' * GENERATED by `pnpm creature-types:generate` (tools/creature-types/generate.ts) from CR 205.3m in',
    ' * docs/rules/comprehensive-rules.txt. Do not edit by hand: tools/creature-types/creature-types.test.ts',
    ' * parses the rules text again and fails when this table differs. The names are spelled as the',
    ' * rules spell them, apostrophes included (C’tan, Shi’ar).',
    ' */',
    'export const CREATURE_TYPES: readonly string[] = [',
    ...types.map((t) => `  '${t}',`),
    '];',
    '',
  ].join('\n');
}

function main(): void {
  const text = renderTable(parseCreatureTypes(readFileSync(CR_FILE, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(TABLE_FILE, 'utf8') !== text) {
      console.error('packages/engine/src/data/creature-types.ts is out of date: run the generator');
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(TABLE_FILE, text);
  console.log(`Wrote ${TABLE_FILE}`);
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
