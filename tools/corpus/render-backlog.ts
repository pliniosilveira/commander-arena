// reports/backlog.md and reports/templates.json

import { type Backlog, type BacklogRow, UNRANKED_WEIGHT } from './backlog.ts';
import { cell, code, groupDigits } from './markdown.ts';
import { headerLine } from './render-coverage.ts';
import type { CorpusResult } from './types.ts';

export const BACKLOG_TEMPLATES_SHOWN = 100;
export const SOLO_TEMPLATES_SHOWN = 50;
/** Templates kept in templates.json (the file stays small enough to commit). */
export const DEFAULT_JSON_TEMPLATES = 1000;

function entry(index: number, row: BacklogRow, solo: boolean): string[] {
  const names = solo ? row.soloTopCards : row.topCards;
  const shown = solo ? row.soloCards : row.cards;
  const weight = solo ? row.soloWeight : row.weight;
  const more = shown > names.length ? `, and ${groupDigits(shown - names.length)} more` : '';
  const lines = [
    `${index}. ${code(cell(row.template))}`,
    solo
      ? `   - Cards unlocked by this shape alone: ${groupDigits(shown)} (of ${groupDigits(row.cards)} it blocks); weight ${weight.toFixed(4)}`
      : `   - Cards blocked: ${groupDigits(shown)}; weight ${weight.toFixed(4)}; ability occurrences ${groupDigits(row.abilities)}; cards that become supported with this shape alone: ${groupDigits(row.soloCards)}`,
    `   - Example: ${code(row.example)}`,
    `   - Cards (most popular first): ${names.map(cell).join('; ')}${more}`,
  ];
  return lines;
}

export function renderBacklog(result: CorpusResult, backlog: Backlog): string {
  const out: string[] = [
    '# Support backlog',
    '',
    headerLine(result),
    '',
    'Generated by `pnpm corpus:templates` or `pnpm coverage:cards`; see docs/CORPUS.md.',
    '',
    '## How the order is chosen',
    '',
    `Each unsupported card contributes its unparsed abilities, grouped by shape (numbers as N, mana costs as {M}). The weight of a card is 1 / EDHREC rank; a card without a rank weighs ${UNRANKED_WEIGHT} (rank 100,000). The weight of a shape is the sum over the distinct cards it blocks. Shapes are ranked by weight, then by cards blocked, then by text. Card names are capped at ten, most popular first. ${groupDigits(backlog.rows.length)} shapes in all; the first ${BACKLOG_TEMPLATES_SHOWN} are listed.`,
    '',
    '## Templates that block cards that have only this one unparsed shape',
    '',
    `Cards whose single blocker is one shape (no other unparsed ability and no other reason, such as an unsupported layout or type) become supported as soon as that shape is learned. These are the cheapest wins. ${groupDigits(backlog.solo.length)} shapes qualify; the first ${SOLO_TEMPLATES_SHOWN} are listed, ranked by the weight of the cards they unlock alone.`,
    '',
  ];
  for (const [i, row] of backlog.solo.slice(0, SOLO_TEMPLATES_SHOWN).entries()) {
    out.push(...entry(i + 1, row, true));
  }
  out.push('', '## Ranked work order', '');
  for (const [i, row] of backlog.rows.slice(0, BACKLOG_TEMPLATES_SHOWN).entries()) {
    out.push(...entry(i + 1, row, false));
  }
  out.push('');
  return out.join('\n');
}

/** Machine-readable form for later tooling: the top `limit` shapes, same order as backlog.md. */
export function renderTemplatesJson(result: CorpusResult, backlog: Backlog, limit: number): string {
  const body = {
    source: result.source,
    parserVersion: result.parserVersion,
    cards: result.cards.length,
    unsupportedCards: result.unsupported.length,
    totalTemplates: backlog.rows.length,
    templates: backlog.rows.slice(0, limit).map((row) => ({
      template: row.template,
      cards: row.cards,
      weight: row.weight,
      abilities: row.abilities,
      example: row.example,
      topCards: row.topCards,
      soloCards: row.soloCards,
      soloWeight: row.soloWeight,
    })),
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}
