// reports/coverage.md

import type { Backlog } from './backlog.ts';
import type { ReasonBreakdownRow, StopRow } from './coverage.ts';
import { cell, code, groupDigits, table } from './markdown.ts';
import { type CorpusResult, type CoverageStats, percent } from './types.ts';

export const FAILURE_SHAPES_SHOWN = 20;
export const STOP_RULES_SHOWN = 15;

export function headerLine(result: CorpusResult): string {
  return `Generated from ${result.source}, ${groupDigits(result.cards.length)} cards, parser version ${result.parserVersion}.`;
}

export function renderCoverage(
  result: CorpusResult,
  stats: CoverageStats,
  reasons: readonly ReasonBreakdownRow[],
  stops: readonly StopRow[],
  backlog: Backlog,
): string {
  const unsupported = result.unsupported.length;
  const population = result.allCards
    ? 'every card in the file'
    : 'Commander-legal cards (legal or restricted)';
  const out: string[] = [
    '# Card coverage',
    '',
    headerLine(result),
    '',
    `Population: ${population}. Generated by \`pnpm coverage:cards\`; see docs/CORPUS.md.`,
    '',
    '## Supported share',
    '',
    ...table(
      ['Population', 'Supported', 'Cards', 'Share'],
      [
        ['All', stats.all, 'all'],
        ['Top 500 by EDHREC rank', stats.top500, 'top500'],
        ['Top 1,000 by EDHREC rank', stats.top1000, 'top1000'],
      ].map(([label, share]) => {
        const s = share as typeof stats.all;
        return [String(label), groupDigits(s.supported), groupDigits(s.total), percent(s)];
      }),
    ),
    '',
    `The top lists take the cards with the lowest \`edhrecRank\`. ${groupDigits(stats.unranked)} of ${groupDigits(result.cards.length)} cards have no rank and are excluded from those two rows (${groupDigits(stats.ranked)} ranked cards).`,
    '',
    '## Input',
    '',
    `- Entries read as cards: ${groupDigits(result.read)}`,
    `- Dropped by the Commander legality filter: ${groupDigits(result.notLegal)}`,
    `- Malformed lines skipped: ${groupDigits(result.malformed)}`,
    `- Rejected (not a usable card, or the import threw): ${groupDigits(result.rejected)}`,
  ];
  for (const problem of result.problems) out.push(`  - ${cell(problem)}`);
  out.push(
    '',
    '## Why cards are unsupported',
    '',
    `${groupDigits(unsupported)} unsupported card(s). A card can have several reasons, so the rows add up to more than the total; "Only" counts the cards with just that one reason.`,
    '',
    ...table(
      ['Reason', 'Cards', 'Only'],
      reasons.map((row) => [cell(row.category), groupDigits(row.cards), groupDigits(row.only)]),
    ),
    '',
    `## Most common failure shapes (top ${FAILURE_SHAPES_SHOWN} by cards blocked)`,
    '',
    'Unparsed ability text with numbers as N and mana costs as {M}. The ranked work order is in backlog.md.',
    '',
    ...table(
      ['Cards', 'Abilities', 'Shape'],
      [...backlog.rows]
        .sort(
          (a, b) => b.cards - a.cards || b.weight - a.weight || (a.template < b.template ? -1 : 1),
        )
        .slice(0, FAILURE_SHAPES_SHOWN)
        .map((row) => [
          groupDigits(row.cards),
          groupDigits(row.abilities),
          code(cell(row.template)),
        ]),
    ),
    '',
    `## Where parsing stopped (top ${STOP_RULES_SHOWN})`,
    '',
    'The closest grammar rule that was tried for each unparsed ability; `none` means no rule matched the start of the text.',
    '',
    ...table(
      ['Closest rule', 'Abilities'],
      stops.slice(0, STOP_RULES_SHOWN).map((row) => [code(row.rule), groupDigits(row.abilities)]),
    ),
    '',
  );
  return out.join('\n');
}
