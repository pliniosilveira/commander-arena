// Splits the test files of a run into shards of about equal time.
//
// Vitest's own `--shard=N/M` sorts the files by a hash of their path and cuts the list into equal counts, so the slowest files can land together: in a green run of the PR tier the four
// shards held 153, 290, 443 and 587 seconds of test files, and the longest one set the time of the whole check. This is the "longest first" greedy method instead (LPT, Graham 1969): take
// the files from the slowest down and give each to the shard that has the least time so far. It is deterministic (every shard job computes the same plan from the same files and the
// same weights, which is what makes the shards a partition) and never worse than 4/3 of the best possible split.
//
// The weights are seconds read from CI logs (`shard-weights.json`, regenerated by `shard-weights.ts`). A stale or missing weight costs balance, never correctness: every file is in
// exactly one shard whatever the weights say.

/** A file the plan places: its path as the sequencer names it and what it is expected to take. */
export interface ShardFile {
  readonly id: string;
  readonly seconds: number;
}

/** The weights of a run: seconds by file path, and what a file that is not listed is taken to cost. */
export interface ShardWeights {
  readonly defaultSeconds: number;
  readonly weights: Readonly<Record<string, number>>;
}

/** The time a file is expected to take: its weight when it has one, else the default (a new file is most likely a light one). */
export function weightOf(weights: ShardWeights, id: string): number {
  return Object.hasOwn(weights.weights, id) ? (weights.weights[id] ?? 0) : weights.defaultSeconds;
}

/**
 * The files of each of `count` shards, in the order of the shard numbers. Every id is in exactly one shard. The result does not depend on the order of `files`: ties in weight
 * go by path, and a tie between shards goes to the lowest shard number.
 */
export function planShards(files: readonly ShardFile[], count: number): string[][] {
  if (!Number.isInteger(count) || count < 1)
    throw new Error(`Shard count must be a positive integer, got ${count}.`);
  const shards: string[][] = Array.from({ length: count }, () => []);
  const load: number[] = Array.from({ length: count }, () => 0);
  const ordered = [...files].sort(
    (a, b) => b.seconds - a.seconds || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
  );
  for (const file of ordered) {
    let lightest = 0;
    for (let i = 1; i < count; i += 1) if ((load[i] ?? 0) < (load[lightest] ?? 0)) lightest = i;
    shards[lightest]?.push(file.id);
    load[lightest] = (load[lightest] ?? 0) + file.seconds;
  }
  return shards;
}

/** The expected time of each shard of a plan under `weights`, for reports and tests. */
export function shardSeconds(
  plan: readonly (readonly string[])[],
  weights: ShardWeights,
): number[] {
  return plan.map((ids) => ids.reduce((sum, id) => sum + weightOf(weights, id), 0));
}
